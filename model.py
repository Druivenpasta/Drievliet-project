def model_acceleration(t, R, r, omega, epsilon, h0, phi,
                       theta, theta_dot, theta_ddot):
    """
    Calculate the model acceleration (ax, ay, az).

    Parameters
    ----------
    t : float
        Time in seconds.
    R, r : float
        Large and small wheel radii.
    omega, epsilon : float
        Angular speeds in radians per second.
    h0 : float
        Reference height.
    phi : float
        Starting phase of the small wheel, in radians.
    theta, theta_dot, theta_ddot : float
        Tilt angle and its first and second time derivatives.

    Returns
    -------
    numpy array
        Acceleration [ax, ay, az].
    """

    A = omega * t
    B = epsilon * t + phi

    C = np.cos(theta)
    S = np.sin(theta)

    cos_A = np.cos(A)
    sin_A = np.sin(A)
    cos_B = np.cos(B)
    sin_B = np.sin(B)

    # -------------------------
    # X acceleration component
    # -------------------------
    ax = R * (
        -(theta_ddot * C
          + theta_dot**2 * S
          + omega**2 * C) * cos_A
        + 2 * omega * theta_dot * S * sin_A
    )

    ax += -r * (epsilon**2 + omega**2) * cos_B * sin_A
    ax += -2 * r * epsilon * omega * sin_B * cos_A

    ax += r * sin_B * cos_A * (
        theta_ddot * C
        + theta_dot**2 * S
        + (omega**2 + epsilon**2) * C
    )

    ax += -2 * r * omega * theta_dot * sin_B * sin_A * S

    ax += 2 * r * epsilon * cos_B * (
        omega * sin_A * C
        + theta_dot * cos_A * S
    )

    # -------------------------
    # Y acceleration component
    # -------------------------
    ay = R * (C * theta_ddot - S * theta_dot**2)

    ay += r * epsilon**2 * sin_B * S
    ay += -2 * r * epsilon * cos_B * C * theta_dot

    ay += -r * sin_B * (
        C * theta_ddot - S * theta_dot**2
    )

    # -------------------------
    # Z acceleration component
    # -------------------------
    az = R * (
        -(theta_ddot * C
          + theta_dot**2 * S
          + omega**2 * C) * sin_A
        - 2 * omega * theta_dot * S * cos_A
    )

    az += r * (epsilon**2 + omega**2) * cos_B * cos_A
    az += -2 * r * epsilon * omega * sin_B * sin_A

    az += r * sin_B * sin_A * (
        (epsilon**2 + omega**2) * C
        + theta_ddot * S
        + theta_dot**2 * C
    )

    az += -2 * r * epsilon * omega * cos_B * cos_A * C
    az += 2 * r * epsilon * theta_dot * cos_B * sin_A * S
    az += 2 * r * omega * theta_dot * sin_B * cos_A * S

    return np.array([ax, ay, az])

    