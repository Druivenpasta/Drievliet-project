def model_acceleration(t, R, r, omega, epsilon, h0, phi,
                       theta, theta_dot, theta_ddot):
    """
    Calculate model acceleration (ax, ay, az).

    Supports scalar or array inputs for t, theta, theta_dot,
    and theta_ddot.

    Returns
    -------
    numpy array
        Shape (3,) for scalar inputs, or (3, N) for N time points.
    """

    t = np.asarray(t)
    theta = np.asarray(theta)
    theta_dot = np.asarray(theta_dot)
    theta_ddot = np.asarray(theta_ddot)

    A = omega * t
    B = epsilon * t + phi

    C = np.cos(theta)
    S = np.sin(theta)

    cos_A = np.cos(A)
    sin_A = np.sin(A)
    cos_B = np.cos(B)
    sin_B = np.sin(B)

    # -------------------------
    # X acceleration component
    # -------------------------
    ax = R * (
        -(theta_ddot * C
          + theta_dot**2 * S
          + omega**2 * C) * cos_A
        + 2 * omega * theta_dot * S * sin_A
    )

    ax += -r * (epsilon**2 + omega**2) * cos_B * sin_A
    ax += -2 * r * epsilon * omega * sin_B * cos_A

    ax += r * sin_B * cos_A * (
        theta_ddot * C
        + theta_dot**2 * S
        + (omega**2 + epsilon**2) * C
    )

    ax += -2 * r * omega * theta_dot * sin_B * sin_A * S

    ax += 2 * r * epsilon * cos_B * (
        omega * sin_A * C
        + theta_dot * cos_A * S
    )

    # -------------------------
    # Y acceleration component
    # -------------------------
    ay = R * (C * theta_ddot - S * theta_dot**2)

    ay += r * epsilon**2 * sin_B * S
    ay += -2 * r * epsilon * cos_B * C * theta_dot

    ay += -r * sin_B * (
        C * theta_ddot - S * theta_dot**2
    )

    # -------------------------
    # Z acceleration component
    # -------------------------
    az = R * (
        -(theta_ddot * C
          + theta_dot**2 * S
          + omega**2 * C) * sin_A
        - 2 * omega * theta_dot * S * cos_A
    )

    az += r * (epsilon**2 + omega**2) * cos_B * cos_A
    az += -2 * r * epsilon * omega * sin_B * sin_A

    az += r * sin_B * sin_A * (
        (epsilon**2 + omega**2) * C
        + theta_ddot * S
        + theta_dot**2 * C
    )

    az += -2 * r * epsilon * omega * cos_B * cos_A * C
    az += 2 * r * epsilon * theta_dot * cos_B * sin_A * S
    az += 2 * r * omega * theta_dot * sin_B * cos_A * S

    return np.stack([ax, ay, az])


    